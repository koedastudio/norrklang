package studio.koeda.norrklang.media

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue
import kotlinx.coroutines.CompletableDeferred
import kotlinx.coroutines.async
import kotlinx.coroutines.test.runTest
import studio.koeda.norrklang.data.model.Track

class HomeMixesSessionTest {
    private class Mixes(
        persistence: MixPersistence<List<String>>? = null,
        private val generateSnapshot: suspend () -> List<String>,
    ) : HomeMixesSession<String, List<String>>(FakeMusicRepository(), persistence) {
        override suspend fun generate() = generateSnapshot()
        override fun isEmpty(snapshot: List<String>) = snapshot.isEmpty()
        override fun sectionTracks(snapshot: List<String>) = emptyMap<String, List<Track>>()
        override suspend fun buildTracksFor(key: String) = emptyList<Track>()
        suspend fun current() = currentSnapshot()
    }

    /** One stored snapshot per fingerprint, as the disk would hold it. */
    private class Disk(private val signedInAs: String? = "acct/all") : MixPersistence<List<String>> {
        val stored = mutableMapOf<String, List<String>>()

        /** Completed by a test to let a read finish; reads return at once when null. */
        var reading: CompletableDeferred<Unit>? = null
        override suspend fun currentFingerprint() = signedInAs
        override suspend fun load(fingerprint: String): List<String>? {
            reading?.await()
            return stored[fingerprint]
        }
        override fun save(fingerprint: String, snapshot: List<String>) {
            stored[fingerprint] = snapshot
        }
    }

    @Test
    fun `the stored snapshot shows before anything is generated`() = runTest {
        val disk = Disk().apply { stored["acct/all"] = listOf("last-drive") }
        val mixes = Mixes(disk) { error("not generated by browsing") }

        assertEquals(listOf("last-drive"), mixes.current())
    }

    @Test
    fun `the first refresh replaces a restored snapshot and stores the new one`() = runTest {
        val disk = Disk().apply { stored["acct/all"] = listOf("last-drive") }
        val mixes = Mixes(disk) { listOf("this-drive") }
        mixes.current()

        assertTrue(mixes.refresh("acct/all"))
        assertFalse(mixes.refresh("acct/all"))

        assertEquals(listOf("this-drive"), mixes.current())
        assertEquals(listOf("this-drive"), disk.stored["acct/all"])
    }

    @Test
    fun `a refresh that generates the same mixes is not a change`() = runTest {
        val disk = Disk().apply { stored["acct/all"] = listOf("same") }
        val mixes = Mixes(disk) { listOf("same") }
        mixes.current()

        assertFalse(mixes.refresh("acct/all"))
    }

    @Test
    fun `a failed generation keeps the restored snapshot and is retried`() = runTest {
        val disk = Disk().apply { stored["acct/all"] = listOf("last-drive") }
        var online = false
        val mixes = Mixes(disk) { if (online) listOf("this-drive") else error("offline") }
        mixes.current()

        assertFalse(mixes.refresh("acct/all"))
        assertEquals(listOf("last-drive"), mixes.current())

        online = true
        assertTrue(mixes.refresh("acct/all"))
    }

    @Test
    fun `a restore during generation does not block the generated snapshot`() = runTest {
        val disk = Disk().apply { stored["acct/all"] = listOf("last-drive") }
        val response = CompletableDeferred<List<String>>()
        val mixes = Mixes(disk) { response.await() }
        val refresh = async { mixes.refresh("acct/all") }
        testScheduler.runCurrent()

        assertEquals(listOf("last-drive"), mixes.current())
        response.complete(listOf("this-drive"))

        assertTrue(refresh.await())
        assertEquals(listOf("this-drive"), mixes.current())
    }

    @Test
    fun `a read that finishes after a sign-out is not adopted`() = runTest {
        val disk = Disk().apply {
            stored["acct/all"] = listOf("old-account")
            reading = CompletableDeferred()
        }
        val mixes = Mixes(disk) { emptyList() }
        val browsing = async { mixes.current() }
        testScheduler.runCurrent()

        mixes.clear()
        disk.reading!!.complete(Unit)

        assertEquals(null, browsing.await())
    }

    @Test
    fun `a read that finishes after a re-scope does not replace the new mixes`() = runTest {
        val disk = Disk().apply {
            stored["acct/all"] = listOf("old-selection")
            reading = CompletableDeferred()
        }
        val mixes = Mixes(disk) { listOf("new-selection") }
        val browsing = async { mixes.current() }
        testScheduler.runCurrent()

        assertTrue(mixes.refresh("acct/2"))
        disk.reading!!.complete(Unit)

        assertEquals(listOf("new-selection"), browsing.await())
    }

    @Test
    fun `nothing is restored when signed out or after clear`() = runTest {
        val signedOut = Mixes(Disk(signedInAs = null).apply { stored["acct/all"] = listOf("x") }) { emptyList() }
        assertEquals(null, signedOut.current())

        val disk = Disk()
        val mixes = Mixes(disk) { listOf("this-drive") }
        mixes.refresh("acct/all")
        mixes.clear()
        disk.stored.clear()
        assertEquals(null, mixes.current())
    }

    @Test
    fun `a changed library selection regenerates under the new fingerprint`() = runTest {
        var generations = 0
        val mixes = Mixes { listOf("mix-${++generations}") }

        assertTrue(mixes.refresh("acct/all"))
        assertFalse(mixes.refresh("acct/all"))
        assertTrue(mixes.refresh("acct/2"))

        assertEquals(2, generations)
        assertEquals(listOf("mix-2"), mixes.current())
    }

    @Test
    fun `a late generation cannot overwrite the replacement account's mixes`() = runTest {
        val oldStarted = CompletableDeferred<Unit>()
        val oldResponse = CompletableDeferred<List<String>>()
        var first = true
        val mixes = Mixes {
            if (first) {
                first = false
                oldStarted.complete(Unit)
                oldResponse.await()
            } else {
                listOf("new-account-mix")
            }
        }
        val oldRefresh = async { mixes.refresh("old-account") }
        oldStarted.await()
        assertTrue(mixes.refresh("new-account"))
        oldResponse.complete(listOf("old-account-mix"))
        assertFalse(oldRefresh.await())
        assertEquals(listOf("new-account-mix"), mixes.current())
    }
}
